# Description: MUL/MULH/MULHSU/MULHU operand walk
#
#   441 operand pairs, each run through the four multiplies and compared with
#   the architectural results precomputed in the table below:
#     rs1 walking one / walking zero (32 + 32) against rs2 = C, and
#     rs2 walking one / walking zero against rs1 = C,
#       for C in {0xFFFFFFFF, 0x80000000, 0x6D2B79F5}          (384 pairs)
#     rs1 = 1<<i against rs2 = ~(1<<i)                          (32 pairs)
#     {0, 1, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF} squared set    (25 pairs)
#   so every operand bit of both ports rises and falls against an all-ones,
#   a sign-only and a mixed partner.
#
#   Unpriv 12.1: "MUL performs an XLEN-bit×XLEN-bit multiplication of rs1 by
#   rs2 and places the lower XLEN bits in the destination register. MULH,
#   MULHU, and MULHSU perform the same multiplication but return the upper
#   XLEN bits of the full 2×XLEN-bit product, for signed×signed,
#   unsigned×unsigned, and rs1×unsigned rs2 multiplication."
#   (MULHSU: rs1 signed.) Unpriv 12.3: "The Zmmul extension implements the
#   multiplication subset of the M extension. It adds all of the
#   instructions defined in Section 12.1, namely: MUL, MULH, MULHU, MULHSU".
#
#   Table row: rs1, rs2, mul, mulh, mulhsu, mulhu (generated offline with
#   Python integer arithmetic).
#   Results: s4 = compares executed (1764), s2 = mismatches (0),
#   s3 = first failing code (pair*4 + op + 1; 0 = none), s5 = its value.
#----------------------------------------------------------------------------

.section .text
.global main

main:
    jal  t0, _random_irq_init
    li   t0, 0

    la   s0, mul_table
    la   s1, mul_table_end
    li   s2, 0
    li   s3, 0
    li   s4, 0
    li   s5, 0
    li   s6, 0                      # pair*4
    li   x31, 0x11111111            # sync: start

.macro CMP res, off, op
    lw   t0, \off(s0)
    addi s4, s4, 1
    beq  \res, t0, 1f
    addi s2, s2, 1
    bnez s3, 1f
    addi s3, s6, \op + 1
    mv   s5, \res
1:
.endm

pair_loop:
    lw     a0, 0(s0)
    lw     a1, 4(s0)
    mul    a2, a0, a1
    mulh   a3, a0, a1
    mulhsu a4, a0, a1
    mulhu  a5, a0, a1
    CMP    a2,  8, 0
    CMP    a3, 12, 1
    CMP    a4, 16, 2
    CMP    a5, 20, 3
    addi   s6, s6, 4
    addi   s0, s0, 24
    bltu   s0, s1, pair_loop

    li   x31, 0xdeadbeef

end_of_test:
    nop
    j    end_of_test

